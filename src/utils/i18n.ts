const LOCALE_KEYS: Record<string, Locale> = {
  en: 'en',
  english: 'en',
  tr: 'tr',
  turkish: 'tr',
  türkçe: 'tr',
};

export function resolveLocale(value: string | undefined): Locale {
  if (!value) return 'en';
  const key = value.toLowerCase();
  if (LOCALE_KEYS[key]) return LOCALE_KEYS[key];
  return 'en';
}

let currentLocale: Locale = 'en';

export function setLocale(locale: Locale): void {
  currentLocale = locale;
}

export function getLocale(): Locale {
  return currentLocale;
}

export function t(key: string, locale: Locale | null = null): string {
  const loc = locale ?? currentLocale;
  const strings = STRINGS[loc];
  if (strings && key in strings) return strings[key]!;
  const en = STRINGS.en;
  if (key in en) return en[key]!;
  return key;
}

export function tn(key: string, _count: number, locale: Locale | null = null): string {
  return tpl(key, { count: _count }, locale);
}

export function tpl(key: string, params: Record<string, string | number>, locale: Locale | null = null): string {
  let value = t(key, locale);
  for (const [name, val] of Object.entries(params)) {
    value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(val));
  }
  return value;
}

export function formatFileSize(bytes: number, locale: Locale | null = null): string {
  const loc = locale ?? currentLocale;
  if (!bytes && bytes !== 0) return '-';
  if (bytes === 0) return loc === 'tr' ? '0 bayt' : '0 B';
  const k = 1024;
  const sizes = loc === 'tr' ? ['bayt', 'KB', 'MB', 'GB'] : ['B', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  const val = parseFloat((bytes / Math.pow(k, i)).toFixed(2));
  return `${val} ${sizes[i] ?? sizes[sizes.length - 1]}`;
}

